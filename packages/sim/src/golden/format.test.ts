import { describe, expect, it } from 'vitest';
import { formatExpected } from './format';

describe('formatExpected', () => {
  const text = formatExpected([
    { name: 'a', result: { hashes: [1, 2, 3], finalStateHash: 3 } },
    { name: 'b', result: { hashes: [], finalStateHash: 9 } },
  ]);

  it('writes one entry per case in the order given, with one hash per line', () => {
    expect(text).toContain(
      "  'a': {\n    hashes: [\n      1,\n      2,\n      3,\n    ],\n    finalStateHash: 3,\n    eventCount: 0,\n  },\n",
    );
    expect(text.indexOf("'a'")).toBeLessThan(text.indexOf("'b'"));
  });

  it('writes an empty hash list for a case with none', () => {
    expect(text).toContain(
      "  'b': {\n    hashes: [\n    ],\n    finalStateHash: 9,\n    eventCount: 0,\n  },\n",
    );
  });

  it('says it is generated and where the goldens change, and fixes the event count at 0', () => {
    expect(text).toContain('GENERATED by `pnpm golden:update`');
    expect(text).toContain('eventCount` is 0 for scripted scenarios');
  });

  it('is a module that exports the expected record, closed properly', () => {
    expect(text).toContain('export const expected: Readonly<Record<string, ExpectedGolden>> = {');
    expect(text.endsWith('};\n')).toBe(true);
  });

  it('is the same text every time for the same results', () => {
    expect(formatExpected([{ name: 'a', result: { hashes: [1], finalStateHash: 1 } }])).toBe(
      formatExpected([{ name: 'a', result: { hashes: [1], finalStateHash: 1 } }]),
    );
  });
});
